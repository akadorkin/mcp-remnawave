// Regenerates docs/TOOLS.md from the built server (npm run build && npm run docs:tools).
// Lists tools as the server registers them; no panel connection is needed.
import fs from 'node:fs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

async function list(readonly) {
    const transport = new StdioClientTransport({
        command: process.execPath,
        args: ['dist/index.js'],
        env: { ...process.env, REMNAWAVE_BASE_URL: 'http://127.0.0.1:1', REMNAWAVE_API_TOKEN: 'doc', REMNAWAVE_READONLY: String(readonly), REMNAWAVE_STATE_DIR: '/tmp/remnawave-mcp-docgen' },
    });
    const client = new Client({ name: 'docgen', version: '1' });
    await client.connect(transport);
    const { tools } = await client.listTools();
    await client.close();
    return tools;
}

const GROUPS = [
    ['Fleet views', (n) => ['fleet_overview', 'inbound_trace', 'host_usage', 'config_search', 'pools_audit'].includes(n)],
    ['Change safety', (n) => ['journal_list', 'backups_list', 'backup_restore', 'api_request'].includes(n)],
    ['Config profiles & inbounds', (n) => n.startsWith('config_profile') || n === 'inbounds_list'],
    ['Subscription templates & pools', (n) => n.startsWith('sub_template') || n === 'pools_edit' || n === 'sub_settings_get'],
    ['Subscriptions', (n) => n.startsWith('subscription')],
    ['Nodes', (n) => n.startsWith('nodes_') || n === 'node_inbounds_edit'],
    ['Hosts', (n) => n.startsWith('hosts_')],
    ['Internal squads', (n) => n.startsWith('squad')],
    ['External squads', (n) => n.startsWith('external_squads')],
    ['Users', (n) => n.startsWith('users_')],
    ['HWID devices', (n) => n.startsWith('hwid_')],
    ['Connections', (n) => n.startsWith('connections_')],
    ['Bandwidth', (n) => n.startsWith('bandwidth_')],
    ['System', (n) => n.startsWith('system_') || n === 'auth_status' || n === 'keygen_get'],
    ['Node plugins & shared lists', (n) => n.startsWith('node_plugins') || n.startsWith('shared_lists')],
    ['Node integrations', (n) => n.startsWith('node_integrations')],
    ['Infra billing', (n) => n.startsWith('billing_')],
    ['Subscription page configs', (n) => n.startsWith('sub_page_configs')],
    ['Snippets, settings, metadata, API tokens', () => true],
];

const all = await list(false);
const ro = new Set((await list(true)).map((t) => t.name));
const first = (d = '') => d.split(/(?<=\.)\s/)[0].replace(/\|/g, '\\|').replace(/\n/g, ' ');
const seen = new Set();
let md = `# Tools\n\nGenerated by \`npm run docs:tools\` — ${all.length} tools, ${ro.size} of them available in read-only mode (✓ in the RO column).\n`;
for (const [title, match] of GROUPS) {
    const ts = all.filter((t) => !seen.has(t.name) && match(t.name));
    if (!ts.length) continue;
    md += `\n## ${title}\n\n| Tool | RO | What it does |\n|---|---|---|\n`;
    for (const t of ts) {
        seen.add(t.name);
        md += `| \`${t.name}\` | ${ro.has(t.name) ? '✓' : ''} | ${first(t.description)} |\n`;
    }
}
fs.writeFileSync('docs/TOOLS.md', md);
console.log(`docs/TOOLS.md: ${all.length} tools`);
